/**
 * Spec data for the drone comparison pages (/compare).
 *
 * Source: DJI's consumer drone comparison page
 * (https://www.dji.com/products/comparison-consumer-drones), read on 14 November 2026.
 * The DJI Mini 4K comes from the UK edition of the same page, which still lists it.
 * Two facts the page leaves out were checked elsewhere: the DJI Flip records 10 bit
 * D Log M (DJI's Flip FAQ), and the Mini 3 Pro gained 10 bit D Cinelike in firmware
 * v01.00.0100.
 *
 * Rules for this file:
 * - Numbers are DJI's own figures for the standard model and standard battery.
 *   Plus battery figures sit in their own fields. Cine and Creator Combo versions
 *   are mentioned in `note`, never mixed into the numbers.
 * - Text that shows on the page is plain English with no dashes or hyphens
 *   (tests/compare.test.mjs checks it). So "1/1.3 inch", "D Log M", "WiFi".
 * - Release years match the shop where the shop lists the drone.
 */

export type Series = "Lito" | "Mini" | "Flip" | "Air" | "Mavic" | "Avata";

/** Camera sensor types DJI uses, with approximate width and height in millimetres. */
export const SENSORS = {
  "4/3": { label: "4/3 inch", w: 17.3, h: 13 },
  "1": { label: "1 inch", w: 13.2, h: 8.8 },
  "1/1.1sq": { label: "1/1.1 inch square", w: 10.3, h: 10.3 },
  "1/1.3": { label: "1/1.3 inch", w: 9.8, h: 7.4 },
  "1/2": { label: "1/2 inch", w: 6.4, h: 4.8 },
  "1/2.3": { label: "1/2.3 inch", w: 6.17, h: 4.55 },
} as const;
export type SensorType = keyof typeof SENSORS;

/** DJI video link systems, oldest first. The index is used for scoring. */
export const LINKS = ["WiFi", "OcuSync 2.0", "O2", "O3", "O3+", "O4", "O4+"] as const;
export type LinkSystem = (typeof LINKS)[number];

/** Flat colour profiles for grading, from none to the most choice. */
export type LogProfile = "none" | "dcinelike" | "dlogm" | "dlog";

export type CompareDrone = {
  slug: string;
  name: string;
  /** Name without "DJI", for tight spaces. */
  short: string;
  series: Series;
  released: number;
  /** False when DJI lists the model as no longer made. */
  current: boolean;
  /** One plain sentence: what this drone is. */
  headline: string;
  /** Extra fact shown under the specs, such as a Cine version. */
  note?: string;
  /** Credited photo in /public (see src/lib/photo-credits.ts). Left out when we have none. */
  image?: string;

  // Travel
  weightG: number;
  /** DJI's wording when it is not a plain number, such as "Under 249 g". */
  weightLabel?: string;
  /** True when the Plus battery takes the drone to 250 g or more. */
  plusOver250?: boolean;
  /** Folded size without propellers, length by width by height in mm. */
  size: [number, number, number];
  folds: boolean;
  /** Built in storage in GB that you can use. 0 means memory card only. */
  storageGB: number;
  storageLabel?: string;

  // Flight
  flightMin: number;
  /** Flight time with the larger Plus battery, where DJI sells one. */
  flightMinPlus?: number;
  windMs: number;
  speedMs: number;
  altitudeM: number;
  batteryWh: number;
  batteryG: number;

  // Camera
  sensor: SensorType;
  /** Number of cameras, and what they are, for the record. */
  cameras: number;
  camerasLabel: string;
  photoMp: number;
  photoLabel?: string;
  /** Widest aperture of the main camera (f number). */
  aperture: number;
  adjustableAperture: boolean;
  raw: boolean;
  /** Longest zoom camera in 35 mm terms, or null for a single wide lens. */
  zoomMm: number | null;
  zoomLabel?: string;

  // Video
  videoLabel: string;
  /** Width in pixels of the largest video size. */
  videoWidth: number;
  /** Highest 4K frame rate, 0 when it has no 4K. */
  fps4k: number;
  /** Highest frame rate at any size, and where. */
  slowFps: number;
  slowLabel: string;
  bitrate: number;
  bitrateLabel?: string;
  tenBit: boolean;
  log: LogProfile;

  // Safety
  sensing: { front: boolean; back: boolean; sides: boolean; up: boolean; down: boolean };
  lidar: boolean;
  guards: boolean;
  link: LinkSystem;
  /** Longest range DJI quotes (FCC, or IC where it is not sold in the US), and the CE figure. */
  rangeKm: number;
  rangeCeKm: number;
  liveView: string;
};

